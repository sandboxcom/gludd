def _infra_binary() -> str | None:
    for name in ("tofu", "terraform"):
        if shutil.which(name):
            return name
    return None


@pytest.fixture(scope="session")
def infra_binary() -> str:
    binary = _infra_binary()
    if binary is None:
        pytest.skip("terraform/tofu not on PATH")
    return binary


def _strip_comments(text: str) -> str:
    return re.sub(r"//.*", "", text)  # strip single-line comments


def _parse_variables(stack_dir: Path) -> dict[str, str]:
    """Extract variable names and defaults from variables.tf.

    Returns a dict mapping variable name → value (original default or
    a synthetic value for required-but-missing vars).
    """
    vars_tf = stack_dir / "variables.tf"
    if not vars_tf.exists():
        return {}
    text = _strip_comments(vars_tf.read_text())

    var_blocks = re.findall(
        r'variable\s+"(\w+)"\s*\{\s*(.+?)\n\}', text, re.DOTALL,
    )
    # Map variable name → (type_str, default_str | None)
    variables: dict[str, tuple[str, str | None]] = {}
    for var_name, body in var_blocks:
        type_match = re.search(r'type\s*=\s*(\w+(?:\([^)]*\))?)', body)
        var_type = type_match.group(1) if type_match else "string"
        default_match = re.search(
            r'default\s*=\s*(.+?)(?:\n\s*\}|\n\}|\n\s*\n|\n\Z)',
            body,
        )
        if default_match:
            raw = default_match.group(1).strip().rstrip(",")
            if raw.startswith('"') and raw.endswith('"'):
                raw = raw[1:-1]
            variables[var_name] = (var_type, raw)
        else:
            variables[var_name] = (var_type, None)

    result: dict[str, str] = {}
    for name, (vtype, default) in variables.items():
        if default is not None:
            result[name] = default
        else:
            result[name] = _synthetic_default(name, vtype)
    return result


def _tfvar_value(val: str) -> str:
    escaped = val.replace("\\", "\\\\").replace('"', '\\"').replace("${", "\\${")
    return f'"{escaped}"'


def _write_tfvars(stack_dir: Path) -> Path:
    vars_dict = _parse_variables(stack_dir)
    lines: list[str] = [
        "# Auto-generated by test_terraform_all_stacks_valid.py",
        "# DO NOT COMMIT",
    ]
    for name, value in vars_dict.items():
        if value.lower() == "true":
            lines.append(f"{name} = true")
        elif value.lower() == "false":
            lines.append(f"{name} = false")
        elif _looks_numeric(value):
            lines.append(f"{name} = {value}")
        else:
            lines.append(f"{name} = {_tfvar_value(value)}")
    tfvars_path = stack_dir / "terraform.auto.tfvars"
    tfvars_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return tfvars_path


def _copy_terraform_tree(destination: Path) -> Path:
    """Copy mutable Terraform inputs outside the checkout and return stacks."""
    copied_root = destination / "terraform"
    shutil.copytree(
        STACKS_DIR.parent.resolve(),
        copied_root,
        ignore=shutil.ignore_patterns(
            ".terraform",
            ".terraform.lock.hcl",
            "terraform.auto.tfvars",
            "*.tfstate",
            "*.tfstate.*",
        ),
    )
    return copied_root / "stacks"


@pytest.fixture(scope="session")
def mutable_stacks_dir(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """Provide a worker-owned Terraform tree for all mutating E2E commands."""
    return _copy_terraform_tree(tmp_path_factory.mktemp("terraform-e2e"))


def _looks_numeric(val: str) -> bool:
    try:
        int(val)
        return True
    except ValueError:
        try:
            float(val)
            return True
        except ValueError:
            return False


def _synthetic_default(var_name: str, var_type: str) -> str:
    if var_type.startswith("number"):
        return "1"
    if var_type.startswith("bool"):
        return "false"
    if var_type.startswith("list"):
        return "[]"
    if var_type.startswith("map"):
        return "{}"
    lower = var_name.lower()
    if "ssh" in lower or "key" in lower:
        return "ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAITest test@example.com"
    if "ami" in lower:
        return "ami-TESTEDNON"
    if "subnet" in lower:
        return "subnet-TESTEDNON"
    if "cidr" in lower:
        return "10.0.0.0/16"
    if "model" in lower:
        return "meta-llama/Llama-3.2-1B-Instruct"
    if "image" in lower or "container" in lower:
        return "alpine:latest"
    if "url" in lower:
        return "https://example.com"
    if "region" in lower:
        return "us-east-1"
    if "kubeconfig" in lower:
        return "~/.kube/config"
    return "test-value"


def _run_infra(
    binary: str, args: list[str], cwd: Path, timeout: int = 120,
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [binary, *args],
        capture_output=True,
        text=True,
        cwd=str(cwd),
        timeout=timeout,
    )


