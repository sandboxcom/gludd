"""E2E: Validate ALL 18 terraform stacks (9 vllm + 9 llamacpp, incl 2 qemu).

Iterates every stack under ``infra/terraform/stacks/``, auto-generates
terraform.tfvars from declared variables, runs ``terraform/opentofu init``
+ ``validate``, and exercises ``DeploymentManager.plan()`` for each
provider-engine combination.  Never applies.

Skips gracefully when the terraform/tofu binary is missing or when a
stack's init fails (network, provider credentials, unsupported platform).
"""

