#!/usr/bin/env python3
"""Frida instrumentation generator for the frida_instrument role.

Generates Frida JavaScript hook scripts and frida CLI invocations for
function interception, memory scanning, SSL pinning bypass, and runtime
tracing via the Stalker API. Report-only — does not invoke frida or attach
to any process.
"""
from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path

VALID_MODES = (
    "function_interception",
    "memory_scanning",
    "ssl_pinning_bypass",
    "tracing",
)

_MODES = {
    "function_interception": "Interceptor.attach hooks for function entry/exit",
    "memory_scanning": "Memory.scan over process ranges with pattern matching",
    "ssl_pinning_bypass": "SSL pinning bypass hooks for BoringSSL / Security.framework",
    "tracing": "Stalker.follow tracing of call/ret/exec events on main thread",
}


def _launcher(frida_tools_path: str) -> str:
    return "{}/frida".format(frida_tools_path.rstrip("/"))


_FUNCTION_INTERCEPTION_SCRIPT = """// Frida function interception harness
// Generated by gludd binary_re.frida_instrument (report-only)

var TARGETS = {targets_json};

function hookSymbol(symbolName) {{
    var addr = Module.findExportByName(null, symbolName);
    if (addr === null) {{
        console.log("[!] symbol not found: " + symbolName);
        return;
    }}
    Interceptor.attach(addr, {{
        onEnter: function (args) {{
            this.t0 = Date.now();
            console.log("[+] enter " + symbolName
                + " arg0=" + args[0].toString()
                + " arg1=" + args[1].toString());
        }},
        onLeave: function (retval) {{
            console.log("[+] leave " + symbolName
                + " ret=" + retval.toString()
                + " ms=" + (Date.now() - this.t0));
        }}
    }});
    console.log("[*] hooked " + symbolName + " @ " + addr);
}}

TARGETS.forEach(hookSymbol);
console.log("[*] interception harness installed; targets=" + TARGETS.length);
"""


def gen_function_interception(
    target: str, targets: list[str], process_spec: str
) -> dict:
    safe_targets = [t for t in targets if t]
    script = _FUNCTION_INTERCEPTION_SCRIPT.format(
        targets_json=json.dumps(safe_targets)
    )
    invocation = "{launcher} -l {{script}} -p {{pid}} -- {process}".format(
        launcher=shlex.quote(_launcher("/usr/local/bin")),
        process=shlex.quote(process_spec),
    )
    return {
        "script": script,
        "script_path": "/tmp/gludd-frida-intercept.js",
        "invocation": invocation,
        "process_spec": process_spec,
        "target_symbols": safe_targets,
    }


_MEMORY_SCAN_SCRIPT = """// Frida memory scanning harness
// Generated by gludd binary_re.frida_instrument (report-only)

var PATTERN = "{pattern}";
var HITS = 0;
var HIT_CAP = {hit_cap};

function scanRange(base, size) {{
    if (HITS >= HIT_CAP) return;
    Memory.scan(base, size, PATTERN, {{
        onMatch: function (address, size) {{
            HITS += 1;
            if (HITS <= HIT_CAP) {{
                console.log("[+] match @ " + address + " size=" + size);
            }}
        }},
        onError: function (reason) {{
            console.log("[!] scan error: " + reason);
        }},
        onComplete: function () {{
            console.log("[*] range done; hits=" + HITS);
        }}
    }});
}}

Process.enumerateRanges({{ protection: "rw-", coalesce: true }}).forEach(function (r) {{
    scanRange(r.base, r.size);
}});
console.log("[*] memory scan complete; total_hits=" + HITS + " cap=" + HIT_CAP);
"""


def gen_memory_scanning(
    target: str, pattern: str, hit_cap: int, process_spec: str
) -> dict:
    safe_pattern = pattern.replace('"', '\\"') or "AA BB CC DD"
    script = _MEMORY_SCAN_SCRIPT.format(
        pattern=safe_pattern, hit_cap=int(hit_cap)
    )
    invocation = "{launcher} -l {{script}} -- {process}".format(
        launcher=shlex.quote(_launcher("/usr/local/bin")),
        process=shlex.quote(process_spec),
    )
    return {
        "script": script,
        "script_path": "/tmp/gludd-frida-memory-scan.js",
        "invocation": invocation,
        "process_spec": process_spec,
        "pattern": safe_pattern,
        "hit_cap": int(hit_cap),
    }


