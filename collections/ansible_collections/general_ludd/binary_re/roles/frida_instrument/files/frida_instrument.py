_TRACING_SCRIPT = """// Frida Stalker tracing harness
// Generated by gludd binary_re.frida_instrument (report-only)

var EVENTS = {{ call: true, ret: {trace_ret}, exec: {trace_exec} }};
var CALL_LOG = [];
var CALL_CAP = {call_cap};

function onReceive(events) {{
    events.forEach(function (ev) {{
        if (CALL_LOG.length < CALL_CAP) {{
            CALL_LOG.push(ev);
        }}
    }});
}}

Stalker.follow(Process.mainThread.id, {{
    events: EVENTS,
    onReceive: function (events) {{
        var parsed = Stalker.parse(events);
        parsed.forEach(function (entry) {{
            if (CALL_LOG.length < CALL_CAP) {{
                CALL_LOG.push(entry);
            }}
        }});
        if (CALL_LOG.length % 100 === 0) {{
            console.log("[*] traced events=" + CALL_LOG.length);
        }}
    }}
}});

setTimeout(function () {{
    Stalker.unfollow(Process.mainThread.id);
    console.log("[*] tracing complete; events=" + CALL_LOG.length
        + " cap=" + CALL_CAP);
}}, {trace_ms});
"""


def gen_tracing(
    target: str,
    process_spec: str,
    trace_ms: int,
    trace_ret: bool,
    trace_exec: bool,
    call_cap: int,
) -> dict:
    script = _TRACING_SCRIPT.format(
        trace_ms=int(trace_ms),
        trace_ret=("true" if trace_ret else "false"),
        trace_exec=("true" if trace_exec else "false"),
        call_cap=int(call_cap),
    )
    invocation = "{launcher} -l {{script}} -- {process}".format(
        launcher=shlex.quote(_launcher("/usr/local/bin")),
        process=shlex.quote(process_spec),
    )
    return {
        "script": script,
        "script_path": "/tmp/gludd-frida-trace.js",
        "invocation": invocation,
        "process_spec": process_spec,
        "trace_ms": int(trace_ms),
        "trace_ret": bool(trace_ret),
        "trace_exec": bool(trace_exec),
        "call_cap": int(call_cap),
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Frida instrumentation generator (report-only)"
    )
    parser.add_argument("--target", required=True, help="Target binary path")
    parser.add_argument("--mode", required=True, choices=VALID_MODES)
    parser.add_argument(
        "--process", default="",
        help="Process spec (name or PID) for frida to attach",
    )
    parser.add_argument(
        "--targets", default="open,read,write",
        help="Comma-separated function symbols (function_interception)",
    )
    parser.add_argument(
        "--pattern", default="",
        help="Hex byte pattern e.g. 'AA BB CC DD' (memory_scanning)",
    )
    parser.add_argument(
        "--hit-cap", type=int, default=1000,
        help="Max matches before memory scan stops",
    )
    parser.add_argument(
        "--trace-ms", type=int, default=5000,
        help="Stalker trace duration in ms (tracing)",
    )
    parser.add_argument(
        "--trace-ret", action="store_true",
        help="Trace return events (tracing)",
    )
    parser.add_argument(
        "--trace-exec", action="store_true",
        help="Trace exec events (tracing — noisy)",
    )
    parser.add_argument(
        "--call-cap", type=int, default=50000,
        help="Max traced events retained (tracing)",
    )
    parser.add_argument("--output", default="-", help="Output file (default stdout)")
    args = parser.parse_args()

    process_spec = args.process or args.target

    if args.mode == "function_interception":
        payload = gen_function_interception(
            args.target, args.targets.split(","), process_spec
        )
    elif args.mode == "memory_scanning":
        payload = gen_memory_scanning(
            args.target, args.pattern, args.hit_cap, process_spec
        )
    elif args.mode == "ssl_pinning_bypass":
        payload = gen_ssl_pinning_bypass(args.target, process_spec)
    elif args.mode == "tracing":
        payload = gen_tracing(
            args.target,
            process_spec,
            args.trace_ms,
            args.trace_ret,
            args.trace_exec,
            args.call_cap,
        )
    else:
        print(f"ERROR: unknown mode {args.mode}", file=sys.stderr)
        sys.exit(2)

    artifact = {
        "target": args.target,
        "mode": args.mode,
        "backend": "report-only",
        **payload,
    }

    text = json.dumps(artifact, indent=2)
    if args.output == "-":
        print(text)
    else:
        Path(args.output).write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
