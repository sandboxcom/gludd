    pkt3 = build_gps_packet(
        version=1, flags=0x01, seq=3, timestamp=1715894402000000,
        lat=37422700000, lon=-122086000000, alt=22, nsats=12, fix=2,
        payload=b"encrypted data stream"
    )
    packets.append(build_udp_packet(12345, 25251, pkt3))

    output_path = "dissector_test_capture.pcap"
    wrpcap(output_path, packets)
