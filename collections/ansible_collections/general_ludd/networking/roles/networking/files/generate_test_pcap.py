def crc16_xmodem(data: bytes) -> int:
    crc = 0xFFFF
    for byte in data:
        crc = CRC_TABLE[((crc >> 8) ^ byte) & 0xFF] ^ ((crc & 0xFF) << 8)
    return crc & 0xFFFF

def build_gps_packet(version, flags, seq, timestamp, lat, lon, alt, nsats, fix, payload):
    payload_len = len(payload)
    header = struct.pack(
        GPS_HEADER_FMT,
        GPS_MAGIC,      # magic
        version,        # version
        flags,          # flags
        seq,            # sequence
        payload_len,    # payload length
        timestamp,      # timestamp
        lat,            # latitude (microdegrees)
        lon,            # longitude (microdegrees)
        alt,            # altitude
        nsats,          # satellites
        fix,            # fix type
        0x0000,         # CRC placeholder
    )
    crc_val = crc16_xmodem(header)
    header = header[:-2] + struct.pack(">H", crc_val)
    return header + payload

def build_udp_packet(src_port, dst_port, payload_bytes):
    from scapy.all import IP, UDP, Raw
    return IP(src="192.168.1.10", dst="192.168.1.20") / \
           UDP(sport=src_port, dport=dst_port) / \
           Raw(load=payload_bytes)

