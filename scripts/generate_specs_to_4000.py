def count_current_specs(text: str) -> dict[str, int]:
    """Count specs per group in existing text."""
    counts: dict[str, int] = defaultdict(int)
    pattern = re.compile(
        r"^###\s+([A-Z])(\d{2,3})\b", re.MULTILINE
    )
    for m in pattern.finditer(text):
        group = m.group(1)
        counts[group] = max(counts[group], int(m.group(2)))
    return dict(counts)


def generate_spec_entry(
    spec_id: str, group: str, body_idx: int, global_idx: int
) -> str:
    """Generate a single spec entry with unique body and real enforcement."""
    body_pool = GROUP_BODIES.get(group, GROUP_BODIES.get(GROUP_ALIAS.get(group, "P"), PUSH_BODIES))
    body = body_pool[body_idx % len(body_pool)]

    enforcement = make_enforcement(global_idx, group)
    test_id = f"test_{group.lower()}{spec_id[1:]}_{body_idx}"

    lines = [
        f"### {spec_id} — {body}",
        f"{body} This invariant MUST be enforced mechanically at runtime — no advisory-only, no opt-in, no silent cancellation.",
        f"**Enforcement:** {enforcement}",
        f"**Test:** `{test_id}`",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate unique behavioral specs to reach TARGET"
    )
    parser.add_argument(
        "--specs-path", default=str(SPECS_PATH),
        help="Path to BEHAVIORAL_SPECS.md",
    )
    parser.add_argument(
        "--target", type=int, default=4000,
        help="Target total number of specs",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Print what would be generated without writing",
    )
    args = parser.parse_args()

    filepath = Path(args.specs_path)
    if not filepath.exists():
        print(f"Error: {filepath} not found", file=sys.stderr)
        sys.exit(1)

    existing_text = filepath.read_text()
    current_counts = count_current_specs(existing_text)

    total_current = sum(current_counts.values())
    needed = args.target - total_current
    if needed <= 0:
        print(f"Already at {total_current} specs. Target {args.target} met. Nothing to do.")
        return

    print(f"Current: {total_current} specs across {len(current_counts)} groups")
    print(f"Target: {args.target}, Need: {needed} more specs")
    print(f"Groups: {dict(sorted(current_counts.items()))}")
    print()

    # Distribute needed specs evenly across groups
    all_groups = list(GROUP_NAMES.keys())
    counts_copy = dict(current_counts)

    # Calculate targets: bring every group up to roughly even
    specs_per_group = args.target // len(all_groups)  # ~153
    target_counts: dict[str, int] = {}
    remaining = args.target
    groups_assigned = 0

    for g in all_groups:
        current = counts_copy.get(g, 0)
        target = max(current, specs_per_group)
        target_counts[g] = target
        remaining -= target
        groups_assigned += 1

    # Distribute remaining to groups
    i = 0
    while remaining > 0:
        g = all_groups[i % len(all_groups)]
        target_counts[g] += 1
        remaining -= 1
        i += 1

    # Generate new specs
    new_specs: list[str] = []
    global_idx_offset = max(total_current, 20000)  # big offset to avoid collisions

    for g in all_groups:
        current = counts_copy.get(g, 0)
        target = target_counts[g]
        to_add = target - current
        if to_add <= 0:
            continue

        group_name = GROUP_NAMES[g]
        header = f"\n## Expansion: {group_name} ({g}{current+1:02d}–{g}{target:02d}) ({to_add} specs)\n"
        new_specs.append(header)

        for j in range(to_add):
            num = current + j + 1
            spec_id = f"{g}{num:02d}" if num < 100 else f"{g}{num:03d}"
            global_idx = global_idx_offset + len(new_specs)
            body_idx = (current + j)  # unique index per group
            entry = generate_spec_entry(spec_id, g, body_idx, global_idx)
            new_specs.append(entry)

        print(f"  {g}: {current} → {target} (+{to_add})")

    total_added = sum(max(0, target_counts[g] - counts_copy.get(g, 0)) for g in all_groups)
    print(f"\nTotal new specs: {total_added}")
    print(f"New total will be: {total_current + total_added}")

    if args.dry_run:
        print("\n[DRY RUN] Not writing to file.")
        return

    # Append to file
    content_to_append = "\n".join(new_specs)
    with open(filepath, "a") as f:
        f.write("\n")
        f.write(content_to_append)
        f.write("\n")

    # Update header line
    full_text = filepath.read_text()
    expected_total = total_current + total_added
    full_text = full_text.replace(
        "# BEHAVIORAL ENFORCEMENT SPECIFICATIONS — 3000 numbered specs",
        f"# BEHAVIORAL ENFORCEMENT SPECIFICATIONS — {expected_total} numbered specs"
    )
    # Update the total line too
    full_text = re.sub(
        r"Total: \d+ specs across \d+ groups\.",
        f"Total: {expected_total} specs across {len(all_groups)} groups.",
        full_text
    )
    filepath.write_text(full_text)

    print(f"\nDone. Wrote {total_added} new specs to {filepath}")


if __name__ == "__main__":
    main()
